import { expect, test } from "vitest";

import { diffRpc } from "../shared/diff";
import { commitAll, inRepository, writeFile } from "../test/repository";
import { readDiff } from "./diff";

const emptied = {
  hunks: [],
  contents: { old: [], new: [] },
  highlights: { old: [], new: [] },
};

const generated = { kind: "text", collapsed: "generated", ...emptied };

function lines(name: string, count: number): string {
  return Array.from({ length: count }, (_, index) => `${name} ${index}\n`).join("");
}

// `lines("a", 1000)` with every other line changed.
const everyOtherLine = Array.from({ length: 1000 }, (_, index) =>
  index % 2 === 0 ? `a ${index}\n` : "b\n",
).join("");

test.each([
  "package-lock.json",
  "npm-shrinkwrap.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "bun.lock",
  "deno.lock",
  "Cargo.lock",
  "Gemfile.lock",
  "composer.lock",
  "poetry.lock",
  "Pipfile.lock",
  "uv.lock",
  "go.sum",
  "mix.lock",
  "flake.lock",
  "devenv.lock",
  "pubspec.lock",
  "Podfile.lock",
  "Package.resolved",
])("collapses the diff of a lockfile named %s, in any directory, as generated", async (name) => {
  await inRepository(async (repository) => {
    const paths = [name, `a/${name}`];

    for (const path of paths) {
      writeFile(repository, path, "a\n");
    }

    commitAll(repository);

    for (const path of paths) {
      writeFile(repository, path, "b\n");
    }

    const diffs = await Promise.all(
      paths.map(async (path) => {
        const diff = await readDiff({ directory: repository, path, side: "unstaged" });

        return diff;
      }),
    );

    expect(diffs).toMatchObject([generated, generated]);
    expect(diffs.map((diff) => diffRpc.output.parse(diff))).toStrictEqual(diffs);
  });
});

test.each([
  ["set", "a linguist-generated", "a", "generated"],
  ["set to true", "a linguist-generated=true", "a", "generated"],
  ["set to another value", "a linguist-generated=yes", "a", "generated"],
  ["unset", "yarn.lock -linguist-generated", "yarn.lock", undefined],
  ["set to false", "yarn.lock linguist-generated=false", "yarn.lock", undefined],
  ["left unspecified", "a linguist-generated\na !linguist-generated", "a", undefined],
])(
  "collapses a file as generated by its linguist-generated attribute, as GitHub does: %s",
  async (_, attributes, path, collapsed) => {
    await inRepository(async (repository) => {
      writeFile(repository, ".gitattributes", `${attributes}\n`);
      writeFile(repository, path, "a\n");

      const diff = await readDiff({ directory: repository, path, side: "unstaged" });

      expect(diff.collapsed).toBe(collapsed);
    });
  },
);

test.each([
  ["1,000 added lines", "", lines("a", 1000), undefined],
  ["1,001 added lines", "", lines("a", 1001), "large"],
  ["501 removed lines and 500 added ones", lines("a", 501), lines("b", 500), "large"],
  ["500 changed lines, each after an unchanged one", lines("a", 1000), everyOtherLine, undefined],
])(
  "collapses as large a diff that adds and removes more than 1,000 lines: %s",
  async (_, head, worktree, collapsed) => {
    await inRepository(async (repository) => {
      writeFile(repository, "a", head);
      commitAll(repository);
      writeFile(repository, "a", worktree);

      const diff = await readDiff({ directory: repository, path: "a", side: "unstaged" });

      expect(diff.collapsed).toBe(collapsed);
      expect(diff.hunks.length === 0).toBe(collapsed !== undefined);
      expect(diffRpc.output.parse(diff)).toStrictEqual(diff);
    });
  },
);

test.each([
  ["generated", "yarn.lock", "a\n", "b\nc\n", { added: 2, removed: 1 }],
  ["large", "a", lines("a", 501), lines("b", 500), { added: 500, removed: 501 }],
])(
  "counts the lines a diff collapsed as %s adds and removes",
  async (collapsed, path, head, worktree, counts) => {
    await inRepository(async (repository) => {
      writeFile(repository, path, head);
      commitAll(repository);
      writeFile(repository, path, worktree);

      const diff = await readDiff({ directory: repository, path, side: "unstaged" });

      expect(diff).toMatchObject({ collapsed, ...counts });
    });
  },
);

test.each([
  ["an empty lockfile", "package-lock.json", ""],
  ["a binary lockfile", "package-lock.json", "\0"],
])("leaves a diff without lines as it is: %s", async (_, path, content) => {
  await inRepository(async (repository) => {
    writeFile(repository, path, content);

    const diff = await readDiff({ directory: repository, path, side: "unstaged" });

    expect(diff.collapsed).toBeUndefined();
  });
});

test("reads a collapsed diff's hunks and contents when asked to expand it, and its version is the same", async () => {
  await inRepository(async (repository) => {
    writeFile(repository, "yarn.lock", "a\n");
    commitAll(repository);
    writeFile(repository, "yarn.lock", "b\n");

    const read = { directory: repository, path: "yarn.lock", side: "unstaged" } as const;
    const collapsed = await readDiff(read);
    const expanded = await readDiff({ ...read, expand: true, entire: true });

    expect(expanded).toStrictEqual({
      version: collapsed.version,
      kind: "text",
      renamedFrom: undefined,
      mode: undefined,
      added: 1,
      removed: 1,
      hunks: [
        {
          oldStart: 1,
          newStart: 1,
          lines: [
            { kind: "removed", text: "a", newline: true },
            { kind: "added", text: "b", newline: true },
          ],
        },
      ],
      contents: { old: ["a"], new: ["b"] },
      highlights: { old: [], new: [] },
    });
    await expect(readDiff({ ...read, expand: false })).resolves.toStrictEqual(collapsed);
  });
});
